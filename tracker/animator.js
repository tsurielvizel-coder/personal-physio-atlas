  function lerp(a, b, t) {
    return a + (b - a) * t;
  }

  function easeCos(t) {
    return 0.5 - 0.5 * Math.cos(Math.PI * t);
  }

  function samplePose(frames, phase) {
    const n = frames.length;
    if (n === 1) return frames[0].p;
    const scaled = phase * (n - 1);
    const i = Math.min(n - 2, Math.floor(scaled));
    const localT = easeCos(scaled - i);
    const a = frames[i].p;
    const b = frames[i + 1].p;
    const out = {};
    for (const k of Object.keys(a)) {
      if (Array.isArray(a[k])) {
        out[k] = [lerp(a[k][0], b[k][0], localT), lerp(a[k][1], b[k][1], localT)];
      } else {
        out[k] = lerp(a[k], b[k], localT);
      }
    }
    return out;
  }

  function sampleFrame(frames, phase) {
    const n = frames.length;
    const idx = Math.min(n - 1, Math.floor(phase * n));
    return frames[idx];
  }

  // Tapered anatomical segment polygon between p1 (width w1) and p2 (width w2)
  function limbPath(p1, p2, w1, w2) {
    const dx = p2[0] - p1[0];
    const dy = p2[1] - p1[1];
    const len = Math.hypot(dx, dy) || 1;
    const nx = -dy / len;
    const ny = dx / len;
    const r1 = w1 * 0.5;
    const r2 = w2 * 0.5;
    const x1a = (p1[0] + nx * r1).toFixed(1), y1a = (p1[1] + ny * r1).toFixed(1);
    const x1b = (p1[0] - nx * r1).toFixed(1), y1b = (p1[1] - ny * r1).toFixed(1);
    const x2a = (p2[0] + nx * r2).toFixed(1), y2a = (p2[1] + ny * r2).toFixed(1);
    const x2b = (p2[0] - nx * r2).toFixed(1), y2b = (p2[1] - ny * r2).toFixed(1);
    return `M ${x1a} ${y1a} L ${x2a} ${y2a} L ${x2b} ${y2b} L ${x1b} ${y1b} Z`;
  }

